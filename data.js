var CUM = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334, 365];
TF.doy = function(s){ var p = s.split('/'); return CUM[+p[0] - 1] + +p[1]; };
TF.md = function(d){ d = TF.wrap(d); for (var m = 12; m >= 1; m--) if (d > CUM[m - 1]) return {m:m, d:d - CUM[m - 1]}; return {m:1, d:1}; };
TF.fmt = function(d){ var x = TF.md(d); return x.m + '/' + x.d; };
TF.wrap = function(d){ return ((Math.round(d) - 1) % 365 + 365) % 365 + 1; };
TF.D0 = 1; TF.D1 = 365;
function rel(d, a){ return ((d - a) % 365 + 365) % 365; }
TF.rel = rel;
