/* 花況：w＝{o,f,e}，d＝年中第幾天（可跨年） */
TF.stageAt = function(w, d){
  var L = rel(w.e, w.o), x = rel(d, w.o), fo = rel(w.f, w.o);
  if (x <= L){
    if (x < fo * .55) return 'open';
    if (x <= fo + (L - fo) * .6) return 'full';
    return 'late';
  }
  return rel(w.o, d) <= 14 ? 'bud' : 'off';
};
/* 花況強度 0～1（給地圖上色用） */
TF.amount = function(w, d){
  var L = rel(w.e, w.o), x = rel(d, w.o), fo = rel(w.f, w.o);
  if (x > L) return 0;
  if (x < fo) return .25 + .75 * Math.pow(x / Math.max(1, fo), .8);
  return 1 - .85 * Math.pow((x - fo) / Math.max(1, L - fo), 1.6);
};
var RANK = {full:0, open:1, late:2, bud:3, off:4};
TF.RANK = RANK;
/* 某地點今天最值得看的花 */
TF.spotBest = function(p, d){
  var best = null;
  p.fl.forEach(function(w){
    var s = TF.stageAt(w, d), k = RANK[s] * 1000 + (s === 'bud' || s === 'off' ? rel(w.o, d) : 0);
    if (!best || k < best.k) best = {w:w, st:s, k:k, fl:TF.flowerById[w.id]};
  });
  return best;
};
TF.spotStage = function(p, d){ return TF.spotBest(p, d).st; };
TF.isPeak = function(st){ return st === 'open' || st === 'full' || st === 'late'; };
TF.spotsOfFlower = function(fid){ return TF.SPOTS.filter(function(p){ return p.fl.some(function(w){ return w.id === fid; }); }); };
TF.winOf = function(p, fid){ for (var i = 0; i < p.fl.length; i++) if (p.fl[i].id === fid) return p.fl[i]; return null; };
/* 花卉在全台的整體花況（取所有地點中最好的那一個） */
TF.flowerStage = function(fid, d){
  var best = 'off', near = 999;
  TF.spotsOfFlower(fid).forEach(function(p){
    var w = TF.winOf(p, fid), s = TF.stageAt(w, d);
    if (RANK[s] < RANK[best]) best = s;
    near = Math.min(near, rel(w.o, d));
  });
  return {st:best, near:near};
};

